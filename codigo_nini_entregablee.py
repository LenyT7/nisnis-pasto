# 3. PROCESAR
# ==============================================================================

anios = [2020, 2021, 2022, 2023, 2024]
todos_jovenes = []

print("\nProcesando archivos...\n")

for anio in anios:
    carpeta = os.path.join(ruta_base, str(anio))
    if not os.path.exists(carpeta):
        print(f"📁 {anio}: carpeta no encontrada")
        continue

    zips = [f for f in os.listdir(carpeta) if f.endswith('.zip')]
    print(f"📁 {anio}: {len(zips)} ZIPs")

    for nombre_zip in sorted(zips):
        ruta_zip = os.path.join(carpeta, nombre_zip)

        df_personas = leer_csv_de_zip(ruta_zip, ['caracteristicas', 'personas', 'generales', 'seguridad social', 'educacion'])
        if df_personas is None:
            continue

        df_ocupados = leer_csv_de_zip(ruta_zip, ['ocupados'])

        if 'P6040' not in df_personas.columns:
            continue

        # Filtro Pasto
        if 'AREA' in df_personas.columns and 'CLASE' in df_personas.columns:
            df_personas['AREA'] = pd.to_numeric(df_personas['AREA'], errors='coerce')
            df_personas['CLASE'] = pd.to_numeric(df_personas['CLASE'], errors='coerce')
            df_pasto = df_personas[(df_personas['AREA'] == 52) & (df_personas['CLASE'] == 1)].copy()
        else:
            df_pasto = df_personas.copy()

        if len(df_pasto) == 0:
            continue

        # Jóvenes 14-28
        df_pasto['EDAD'] = pd.to_numeric(df_pasto['P6040'], errors='coerce')
        df_jovenes = df_pasto[(df_pasto['EDAD'] >= 14) & (df_pasto['EDAD'] <= 28)].copy()

        if len(df_jovenes) == 0:
            continue

        # EXCLUIR MESES QUE NO FILTRARON PASTO
        if len(df_jovenes) > 1000:
            print(f"   {nombre_zip}: {len(df_jovenes)} jóvenes - EXCLUIDO")
            continue

        # Variables
        df_jovenes['ANIO'] = anio

        # Sexo
        if 'P6020' in df_jovenes.columns:
            df_jovenes['MUJER'] = (pd.to_numeric(df_jovenes['P6020'], errors='coerce') == 2).astype(int)
        else:
            df_jovenes['MUJER'] = 0

        # Nivel educativo
        if 'P6210' in df_jovenes.columns:
            df_jovenes['NIVEL_ED'] = pd.to_numeric(df_jovenes['P6210'], errors='coerce')
        else:
            df_jovenes['NIVEL_ED'] = np.nan

        # Factor de expansión
        if 'FEX_C' in df_jovenes.columns:
            df_jovenes['FEX_C'] = pd.to_numeric(df_jovenes['FEX_C'], errors='coerce')
        elif 'FEX_C18' in df_jovenes.columns:
            df_jovenes['FEX_C'] = pd.to_numeric(df_jovenes['FEX_C18'], errors='coerce')
        else:
            df_jovenes['FEX_C'] = np.nan

        df_jovenes['FEX_C'] = df_jovenes['FEX_C'].fillna(1)
        df_jovenes.loc[df_jovenes['FEX_C'] <= 0, 'FEX_C'] = 1

        # NINI a nivel de persona
        if 'P6170' in df_jovenes.columns:
            no_estudia = pd.to_numeric(df_jovenes['P6170'], errors='coerce') != 1
        else:
            no_estudia = pd.Series(True, index=df_jovenes.index)

        if df_ocupados is not None and 'DIRECTORIO' in df_ocupados.columns and 'ORDEN' in df_ocupados.columns:
            df_ocupados['ID_PERSONA'] = (
                df_ocupados['DIRECTORIO'].astype(str).str.strip() + '_' +
                df_ocupados['ORDEN'].astype(str).str.strip()
            )
            personas_trabajan = set(df_ocupados['ID_PERSONA'].unique())

            if 'ORDEN' in df_jovenes.columns:
                df_jovenes['ID_PERSONA'] = (
                    df_jovenes['DIRECTORIO'].astype(str).str.strip() + '_' +
                    df_jovenes['ORDEN'].astype(str).str.strip()
                )
                no_trabaja = ~df_jovenes['ID_PERSONA'].isin(personas_trabajan)
            else:
                no_trabaja = pd.Series(True, index=df_jovenes.index)
        else:
            no_trabaja = pd.Series(True, index=df_jovenes.index)

        df_jovenes['NINI'] = (no_estudia & no_trabaja).astype(int)

        todos_jovenes.append(df_jovenes)
        print(f"   {nombre_zip}: {len(df_jovenes)} jóvenes, {df_jovenes['NINI'].sum()} NINI")

# ==============================================================================
