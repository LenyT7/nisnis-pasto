# ==============================================================================

print("\n" + "="*60)
print("CONSOLIDANDO DATOS")
print("="*60)

if len(todos_jovenes) == 0:
    print("⚠️ No se procesaron datos")
else:
    df = pd.concat(todos_jovenes, ignore_index=True)

    print(f"Total jóvenes: {len(df):,}")
    print(f"Total NINI: {df['NINI'].sum():,} ({df['NINI'].mean():.1%})")
    print(f"Con FEX_C > 1: {(df['FEX_C'] > 1).sum():,}")

    # ==============================================================================
    # 5. CARACTERIZACIÓN PONDERADA
    # ==============================================================================
    print("\n" + "="*60)
    print("📊 CARACTERIZACIÓN (PONDERADA CON FEX_C)")
    print("="*60)

    print("\n1. Prevalencia por año:")
    for anio in sorted(df['ANIO'].unique()):
        df_anio = df[df['ANIO'] == anio]
        prev = np.average(df_anio['NINI'], weights=df_anio['FEX_C'])
        print(f"   {anio}: {prev:.1%} (N={len(df_anio):,})")

    prev_total = np.average(df['NINI'], weights=df['FEX_C'])
    print(f"\n   TOTAL: {prev_total:.1%}")

    print("\n2. Por sexo:")
    for sexo, nombre in [(0, 'Hombres'), (1, 'Mujeres')]:
        df_s = df[df['MUJER'] == sexo]
        if len(df_s) > 0:
            prev = np.average(df_s['NINI'], weights=df_s['FEX_C'])
            print(f"   {nombre}: {prev:.1%}")

    df['GRUPO_EDAD'] = pd.cut(df['EDAD'], bins=[13, 17, 21, 24, 28],
                              labels=['14-17', '18-21', '22-24', '25-28'])
    print("\n3. Por grupo de edad:")
    for grupo in ['14-17', '18-21', '22-24', '25-28']:
        df_g = df[df['GRUPO_EDAD'] == grupo]
        if len(df_g) > 0:
            prev = np.average(df_g['NINI'], weights=df_g['FEX_C'])
            print(f"   {grupo}: {prev:.1%}")

    print("\n4. Por nivel educativo:")
    niveles_nombre = {1: 'Ninguno', 2: 'Preescolar', 3: 'Primaria', 4: 'Media', 5: 'Técnica', 6: 'Superior'}
    for nivel in sorted(df['NIVEL_ED'].dropna().unique()):
        df_n = df[df['NIVEL_ED'] == nivel]
        if len(df_n) > 10:
            prev = np.average(df_n['NINI'], weights=df_n['FEX_C'])
            nombre = niveles_nombre.get(int(nivel), f'Nivel {int(nivel)}')
            print(f"   {nombre}: {prev:.1%}")

    # ==============================================================================
    # 6. MODELO LOGIT CON PESOS (MÉTODO CORREGIDO)
    # ==============================================================================
    print("\n" + "="*60)
    print("📈 MODELO LOGIT CON PESOS")
    print("="*60)

    df_modelo = df.dropna(subset=['NINI', 'MUJER', 'EDAD', 'NIVEL_ED', 'FEX_C']).copy()
    print(f"Observaciones: {len(df_modelo):,}")

    if len(df_modelo) >= 100:
        df_modelo['EDAD_C'] = df_modelo['EDAD'] - df_modelo['EDAD'].mean()
        df_modelo['EDAD_C2'] = df_modelo['EDAD_C'] ** 2

        df_modelo['NIVEL_AGRUP'] = pd.cut(
            df_modelo['NIVEL_ED'],
            bins=[0, 3, 4, 10],
            labels=['Bajo', 'Medio', 'Alto']
        )

        formula = "NINI ~ MUJER + EDAD_C + EDAD_C2 + C(NIVEL_AGRUP, Treatment(reference='Medio')) + C(ANIO)"

        # ========== MÉTODO CORREGIDO: REMUESTREO PONDERADO ==========
        # Normalizar pesos
        pesos = df_modelo['FEX_C'] / df_modelo['FEX_C'].sum()

        # Crear muestra ponderada (bootstrap ponderado)
        np.random.seed(42)
        indices = np.random.choice(
            df_modelo.index,
            size=len(df_modelo),
            replace=True,
            p=pesos
        )
        df_pond = df_modelo.loc[indices].copy()

        print(f"Muestra ponderada: {len(df_pond):,}")

        # Estimar modelo
        modelo = smf.logit(formula=formula, data=df_pond)
        resultado = modelo.fit(disp=False, maxiter=100, cov_type='HC1')

        print(resultado.summary())

        print("\n📉 Efectos marginales (AME):")
        margeff = resultado.get_margeff(at='overall')
        print(margeff.summary())

        # Guardar efectos para uso posterior
        print("\n📋 RESUMEN DE EFECTOS:")
        print(f"   Educación baja: {margeff.margeff[0]*100:+.1f} pp")
        print(f"   Educación alta: {margeff.margeff[1]*100:+.1f} pp")
        print(f"   Año 2021: {margeff.margeff[2]*100:+.1f} pp")
        print(f"   Mujer: {margeff.margeff[3]*100:+.1f} pp")
        print(f"   Edad (+1 año): {margeff.margeff[4]*100:+.1f} pp")
    else:
        print("Muy pocas observaciones")

    print("\n" + "="*60)
    print("✅ ANÁLISIS COMPLETADO")
    print("="*60)

